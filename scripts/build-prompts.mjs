// Builds src/lib/prompt-text.ts from the written method in docs/ (so the deployed app carries the
// exact prompts, and editing the docs is how the prompts change). Runs before dev and build.
import { readFileSync, writeFileSync } from "node:fs";
const read = (p) => readFileSync(new URL(`../docs/${p}`, import.meta.url), "utf8");
const afterRule = (s) => s.split(/^---\s*$/m).slice(1).join("---").trim();
const partA = (s) => { const a = s.indexOf("## Part A"), b = s.indexOf("## Part B"); return s.slice(a, b > a ? b : undefined).trim(); };

const method = afterRule(read("methodology/01-teaching-method.md"));
const research = partA(read("methodology/02-research-method.md"));
const out = {
  METHOD: method,
  RESEARCH: research,
  STORY: afterRule(read("app-prompts/story.md")),
  OUTLINE: afterRule(read("app-prompts/course-outline.md")),
  LESSON: afterRule(read("app-prompts/lesson.md")),
};
const ts = `// GENERATED by scripts/build-prompts.mjs from docs/methodology and docs/app-prompts. Do not edit.\n` +
  Object.entries(out).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`).join("\n") + "\n";
writeFileSync(new URL("../src/lib/prompt-text.ts", import.meta.url), ts);
console.log("prompts:", Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.split(/\s+/).length + " words"])));
